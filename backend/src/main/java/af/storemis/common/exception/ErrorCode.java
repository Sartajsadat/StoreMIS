package af.storemis.common.exception;

import org.springframework.http.HttpStatus;

/** Stable, language-neutral error codes. Each has a matching {@code errors.<CODE>} key in the frontend translations. */
public enum ErrorCode {
    GENERIC(HttpStatus.INTERNAL_SERVER_ERROR),
    VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
    UNAUTHORIZED(HttpStatus.UNAUTHORIZED),
    FORBIDDEN(HttpStatus.FORBIDDEN),
    NOT_FOUND(HttpStatus.NOT_FOUND),
    OPTIMISTIC_LOCK(HttpStatus.CONFLICT),
    DUPLICATE(HttpStatus.CONFLICT),

    INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED),
    ACCOUNT_DISABLED(HttpStatus.UNAUTHORIZED),
    ACCOUNT_LOCKED(HttpStatus.UNAUTHORIZED),
    SESSION_EXPIRED(HttpStatus.UNAUTHORIZED),
    PASSWORD_INCORRECT(HttpStatus.UNPROCESSABLE_ENTITY),
    PASSWORD_WEAK(HttpStatus.UNPROCESSABLE_ENTITY),
    PASSWORD_CHANGE_REQUIRED(HttpStatus.FORBIDDEN),
    CANNOT_MODIFY_SELF(HttpStatus.UNPROCESSABLE_ENTITY),
    LAST_ADMIN(HttpStatus.UNPROCESSABLE_ENTITY),

    FILE_TOO_LARGE(HttpStatus.PAYLOAD_TOO_LARGE),
    FILE_TYPE_NOT_ALLOWED(HttpStatus.UNSUPPORTED_MEDIA_TYPE),

    STOCK_INSUFFICIENT(HttpStatus.CONFLICT),
    QUANTITY_NOT_INTEGER(HttpStatus.UNPROCESSABLE_ENTITY),
    OPENING_STOCK_EXISTS(HttpStatus.CONFLICT),
    PRODUCT_INACTIVE(HttpStatus.UNPROCESSABLE_ENTITY),
    UNIT_COST_REQUIRED(HttpStatus.UNPROCESSABLE_ENTITY),
    CASH_INSUFFICIENT(HttpStatus.CONFLICT),
    EXCHANGE_RATE_MISSING(HttpStatus.UNPROCESSABLE_ENTITY),
    CURRENCY_MISMATCH(HttpStatus.UNPROCESSABLE_ENTITY),
    OPENING_BALANCE_EXISTS(HttpStatus.CONFLICT),
    INVALID_STATE(HttpStatus.CONFLICT),
    AMOUNT_EXCEEDS_TOTAL(HttpStatus.UNPROCESSABLE_ENTITY),
    DISCOUNT_TOO_LARGE(HttpStatus.UNPROCESSABLE_ENTITY),
    SUPPLIER_INACTIVE(HttpStatus.UNPROCESSABLE_ENTITY),
    CUSTOMER_INACTIVE(HttpStatus.UNPROCESSABLE_ENTITY),
    DISCOUNT_NOT_ALLOWED(HttpStatus.FORBIDDEN),
    WALK_IN_MUST_PAY(HttpStatus.UNPROCESSABLE_ENTITY),
    SALE_BELOW_COST(HttpStatus.UNPROCESSABLE_ENTITY),
    OVERPAYMENT(HttpStatus.UNPROCESSABLE_ENTITY),
    ALLOCATION_INVALID(HttpStatus.UNPROCESSABLE_ENTITY),
    DAY_CLOSED(HttpStatus.CONFLICT),
    RETURN_QUANTITY_EXCEEDED(HttpStatus.UNPROCESSABLE_ENTITY);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }

    public HttpStatus status() {
        return status;
    }
}
